/**
 * Dev-only eval-results browser: pick a run → pick a topic → every beat plays
 * through the real SceneRenderer with its deterministic score breakdown.
 * Reads eval-results/ from the filesystem (created by `npm run eval`), so this
 * page only works on the machine that ran the eval — which is the point.
 */

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import Link from "next/link";

import EvalLessonViewer from "@/components/EvalLessonViewer";
import type { Lesson } from "@/types/lesson";
import type { LessonScoreSummary } from "@/lib/sceneScore";

export const dynamic = "force-dynamic";

const ROOT = join(process.cwd(), "eval-results");
const safe = (s: string) => /^[a-zA-Z0-9_-]+$/.test(s);

interface RunIndex {
  createdAt: string;
  provider: string;
  model: string;
  offline: boolean;
  meanOfMeans: number;
  minOfMins: number;
  results: { topic: string; title: string; beats: number; scores: { mean: number; min: number; weakestPart: string } }[];
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);

export default async function EvalPage({ searchParams }: { searchParams: Promise<{ run?: string; topic?: string }> }) {
  const { run, topic } = await searchParams;

  const runs = existsSync(ROOT)
    ? readdirSync(ROOT, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name)
        .sort()
        .reverse()
    : [];

  let index: RunIndex | null = null;
  let lessonData: { topic: string; lesson: Lesson; scores: LessonScoreSummary } | null = null;

  if (run && safe(run)) {
    const indexPath = join(ROOT, run, "index.json");
    if (existsSync(indexPath)) index = JSON.parse(readFileSync(indexPath, "utf8")) as RunIndex;
    if (topic && safe(topic)) {
      const topicPath = join(ROOT, run, `${topic}.json`);
      if (existsSync(topicPath)) lessonData = JSON.parse(readFileSync(topicPath, "utf8"));
    }
  }

  return (
    <main className="min-h-screen bg-black px-6 py-8 text-white">
      <h1 className="mb-1 text-xl font-semibold">Eval results</h1>
      <p className="mb-6 text-sm opacity-60">Generated by npm run eval · deterministic sceneScore judge</p>

      {!runs.length && <p className="text-sm opacity-70">No eval-results/ yet. Run npm run eval first.</p>}

      <div className="mb-6 flex flex-wrap gap-2">
        {runs.map((r) => (
          <Link
            key={r}
            href={`/debug/eval?run=${r}`}
            className={`rounded px-3 py-1 text-xs ${r === run ? "bg-white text-black" : "bg-white/10 hover:bg-white/20"}`}
          >
            {r}
          </Link>
        ))}
      </div>

      {index && (
        <div className="mb-8">
          <p className="mb-3 text-sm opacity-80">
            {index.provider} / {index.model} · overall mean <b>{index.meanOfMeans}</b> · min <b>{index.minOfMins}</b>
            {index.offline ? " · offline" : ""}
          </p>
          <div className="flex flex-col gap-1">
            {index.results.map((r) => (
              <Link
                key={r.topic}
                href={`/debug/eval?run=${run}&topic=${slug(r.topic)}`}
                className={`rounded px-3 py-2 text-sm ${slug(r.topic) === topic ? "bg-white/20" : "hover:bg-white/10"}`}
              >
                <span className="font-medium">{r.topic}</span>
                <span className="ml-3 opacity-60">
                  {r.beats} beats · mean {r.scores.mean} · min {r.scores.min} · weakest {r.scores.weakestPart}
                </span>
              </Link>
            ))}
          </div>
        </div>
      )}

      {lessonData && (
        <div className="border-t border-white/10 pt-6">
          <h2 className="mb-4 text-lg font-medium">{lessonData.lesson.title}</h2>
          <EvalLessonViewer lesson={lessonData.lesson} scores={lessonData.scores} />
        </div>
      )}
    </main>
  );
}
